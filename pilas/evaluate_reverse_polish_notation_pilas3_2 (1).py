# Complejidad temporal: O(n)
# Complejidad espacial: O(n)
# Justificación: Se procesa cada token del arreglo de longitud n una sola vez.
# La pila puede almacenar hasta O(n) números en el peor de los casos. Las
# operaciones de inserción, extracción y operaciones aritméticas son O(1).

class Solution:
    def evalRPN(self, tokens: list[str]) -> int:
        pila = []

        for token in tokens:
            if token in {"+", "-", "*", "/"}:
                b = pila.pop()
                a = pila.pop()

                if token == "+":
                    pila.append(a + b)
                elif token == "-":
                    pila.append(a - b)
                elif token == "*":
                    pila.append(a * b)
                elif token == "/":
                    # La división debe truncar hacia cero en Python
                    pila.append(int(a / b))
            else:
                pila.append(int(token))

        return pila[0]
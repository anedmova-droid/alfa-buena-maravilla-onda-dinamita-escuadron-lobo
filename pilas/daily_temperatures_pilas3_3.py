# Complejidad temporal: O(n)
# Complejidad espacial: O(n)
# Justificación: Aunque hay un ciclo anidado (while), cada índice de la lista de temperaturas se agrega (append) y remueve (pop) de la pila a lo más una vez, logrando un tiempo amortizado de O(n). La pila y la lista de respuesta ocupan O(n) espacio.

class Solution:
    def dailyTemperatures(self, temperatures: list[int]) -> list[int]:
        n = len(temperatures)
        respuesta = [0] * n
        pila = []  # Pila monótona que guarda índices

        for i, temp in enumerate(temperatures):
            while pila and temperatures[pila[-1]] < temp:
                indice_previo = pila.pop()
                respuesta[indice_previo] = i - indice_previo
            pila.append(i)

        return respuesta